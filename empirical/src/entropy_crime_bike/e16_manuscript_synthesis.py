import pandas as pd


def _sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _accepted(pointer: Path, stage: str) -> Path:
    run = Path(pointer.read_text(encoding="utf-8").strip())
    status = json.loads((run / "run_status.json").read_text(encoding="utf-8"))
    if status.get("status") != "complete" or status.get("stage") != stage:
        raise ValueError(f"Expected accepted {stage}: {run}")
    return run


def _write_macros(path: Path, stability: pd.DataFrame, normalized: pd.DataFrame, randomization: pd.DataFrame) -> None:
    mm_full = normalized.loc[
        normalized["estimator"].eq("miller_madow") & normalized["fraction"].eq(1)
    ]
    aggregate = (
        stability.loc[stability["estimator"].eq("miller_madow") & stability["fraction"].lt(1)]
        .groupby("fraction", as_index=False)
        .agg(
            bound=("stability_l0_exact_mse_median", "median"),
            cmi=("stability_delta_h_raw_bits_median", "median"),
        )
    )
    lines = [
        "% Auto-generated by empirical/run_e16_manuscript_synthesis.py.",
        f"\\newcommand{{\\ScaleRandomizationRows}}{{{161730:,}}}",
        f"\\newcommand{{\\ScaleRandomizationTests}}{{{len(randomization)}}}",
        f"\\newcommand{{\\ScaleGlobalDiscoveries}}{{{int(randomization['separates_global_fdr'].sum())}}}",
        f"\\newcommand{{\\ScaleCityDesignDiscoveries}}{{{int(randomization['separates_city_design_fdr'].sum())}}}",
        f"\\newcommand{{\\ScaleMinimumRawP}}{{{randomization['randomization_p_value'].min():.3f}}}",
        f"\\newcommand{{\\ScaleMinimumWithinQ}}{{{randomization['q_value_city_design_bh'].min():.3f}}}",
        f"\\newcommand{{\\ScalePositiveObservedNull}}{{{int((randomization['observed_minus_null_mean_bits'] > 0).sum())}}}",
        f"\\newcommand{{\\ScaleFullCMIMin}}{{{mm_full['delta_h_raw_bits'].min():.4f}}}",
        f"\\newcommand{{\\ScaleFullCMIMax}}{{{mm_full['delta_h_raw_bits'].max():.4f}}}",
        f"\\newcommand{{\\ScaleSingletonMin}}{{{mm_full['singleton_observation_share'].min():.4f}}}",
        f"\\newcommand{{\\ScaleSingletonMax}}{{{mm_full['singleton_observation_share'].max():.4f}}}",
        f"\\newcommand{{\\ScaleIntensityReductionMin}}{{{mm_full['delta_exact_intensity_rmse'].min():.4f}}}",
        f"\\newcommand{{\\ScaleIntensityReductionMax}}{{{mm_full['delta_exact_intensity_rmse'].max():.4f}}}",
    ]
    for row in aggregate.itertuples(index=False):
        percent = int(round(row.fraction * 100))
        suffix = {20: "Twenty", 40: "Forty", 60: "Sixty", 80: "Eighty"}[percent]
        lines.append(f"\\newcommand{{\\ScaleBoundStability{suffix}}}{{{row.bound:.3f}}}")
        lines.append(f"\\newcommand{{\\ScaleCMIStability{suffix}}}{{{row.cmi:.3f}}}")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def _stability_table(path: Path, stability: pd.DataFrame) -> None:
    table = (
        stability.loc[stability["estimator"].eq("miller_madow")]
        .groupby("fraction", as_index=False)
        .agg(
            baseline=("stability_l0_exact_mse_median", "median"),
            bicycle=("stability_lb_exact_mse_median", "median"),
            reduction=("stability_delta_l_exact_mse_median", "median"),
            cmi=("stability_delta_h_raw_bits_median", "median"),
        )
    )
    lines = [
        "\\begin{table}[H]",
        "\\caption{Median relative deviation from the 100\\% estimate across the 18 city--space--time cells. Quantiles over thinning repetitions are design-variability summaries, not population confidence intervals.}",
        "\\label{tab:e16_sample_stability}",
        "\\centering",
        "\\begin{tabular}{ccccc}",
        "\\toprule",
        "\\textbf{Sample fraction} & \\textbf{Baseline DELB} & \\textbf{Bicycle DELB} & \\textbf{DELB reduction} & \\textbf{CMI}\\\\",
        "\\midrule",
    ]
    for row in table.itertuples(index=False):
        lines.append(f"{int(round(row.fraction*100))}\\% & {row.baseline:.3f} & {row.bicycle:.3f} & {row.reduction:.3f} & {row.cmi:.3f}\\\\")
    lines.extend(["\\bottomrule", "\\end{tabular}", "\\end{table}"])
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def _randomization_table(path: Path, summary: pd.DataFrame) -> None:
    rows = (
        summary.groupby("null_design", as_index=False)
        .agg(
            tests=("randomization_p_value", "size"),
            min_p=("randomization_p_value", "min"),
            median_p=("randomization_p_value", "median"),
            positive=("observed_minus_null_mean_bits", lambda value: int((value > 0).sum())),
            discoveries=("separates_global_fdr", "sum"),
        )
        .set_index("null_design")
        .loc[["temporal_block", "spatial_series", "circular_shift"]]
        .reset_index()
    )
    labels = {"temporal_block": "Temporal block", "spatial_series": "Spatial series", "circular_shift": "Circular shift"}
    lines = [
        "\\begin{table}[H]",
        "\\caption{Multiscale upper-tail randomization calibration. Discoveries use a Benjamini--Hochberg adjustment across all 270 tests.}",
        "\\label{tab:e16_randomization_summary}",
        "\\begin{adjustwidth}{-\\extralength}{0cm}",
        "\\centering",
        "\\small",
        "\\begin{tabular}{lccccc}",
        "\\toprule",
        "\\textbf{Null design} & \\textbf{Tests} & \\textbf{Min. $p$} & \\textbf{Median $p$} & \\textbf{Obs. $>$ null} & \\textbf{FDR discoveries}\\\\",
        "\\midrule",
    ]
    for row in rows.itertuples(index=False):
        lines.append(f"{labels[row.null_design]} & {int(row.tests)} & {row.min_p:.3f} & {row.median_p:.3f} & {int(row.positive)} & {int(row.discoveries)}\\\\")
    lines.extend(["\\bottomrule", "\\end{tabular}", "\\end{adjustwidth}", "\\end{table}"])
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def run(args: argparse.Namespace) -> Path:
    started = time.monotonic()
    project = Path(args.project).resolve()
    empirical = project / "empirical"
    s16_5 = _accepted(empirical / "runs/latest_e16_s16_5_run.txt", "S16.5")
    s16_6 = _accepted(empirical / "runs/latest_e16_s16_6_run.txt", "S16.6")
    timezone = ZoneInfo("Asia/Shanghai")
    run_id = datetime.now(timezone).strftime("%Y%m%d_%H%M%S") + "_E16_S16_7_manuscript_synthesis"
    run_dir = empirical / "runs" / run_id
    for directory in [run_dir / "tables", run_dir / "figures"]:
        directory.mkdir(parents=True, exist_ok=True)
    (run_dir / "command.txt").write_text(" ".join([sys.executable, *sys.argv]) + "\n", encoding="utf-8")
    (run_dir / "environment.txt").write_text(
        f"timestamp={datetime.now().isoformat()}\npython={sys.version.replace(os.linesep, ' ')}\nplatform={platform.platform()}\npandas={pd.__version__}\n",
        encoding="utf-8",
    )

    stability = pd.read_csv(s16_5 / "tables/sample_stability_summary.csv")
    normalized = pd.read_parquet(s16_5 / "tables/primary_normalized_estimates.parquet")
    randomization = pd.read_csv(s16_6 / "tables/randomization_summary.csv")
    generated = project / "sections/generated/e16"
    generated.mkdir(parents=True, exist_ok=True)
    _write_macros(generated / "e16_macros.tex", stability, normalized, randomization)
    _stability_table(generated / "table_e16_sample_stability.tex", stability)
    _randomization_table(generated / "table_e16_randomization.tex", randomization)

    figure_dir = project / "figures/e16"
    figure_dir.mkdir(parents=True, exist_ok=True)
    copied = []
    for source_run in [s16_5, s16_6]:
        for source in sorted((source_run / "figures").iterdir()):
            destination = figure_dir / source.name
            shutil.copy2(source, destination)
            if _sha256(source) != _sha256(destination):
                raise AssertionError(f"Figure copy hash mismatch: {source.name}")
            copied.append({"source": str(source), "destination": str(destination), "sha256": _sha256(destination)})
    pd.DataFrame(copied).to_csv(run_dir / "tables/figure_copy_manifest.csv", index=False)

    generated_files = sorted(generated.glob("*.tex"))
    checks = pd.DataFrame(
        [
            ("accepted S16.5", True),
            ("accepted S16.6", True),
            ("generated LaTeX files", len(generated_files) == 3),
            ("hash-verified figure copies", len(copied) == 12),
            ("randomization tests", len(randomization) == 270),
            ("global discoveries preserved", int(randomization["separates_global_fdr"].sum()) == 0),
        ],
        columns=["check", "passed"],
    )
    checks.to_csv(run_dir / "tables/acceptance_checklist.csv", index=False)
    if not checks["passed"].all():
        raise AssertionError("S16.7 synthesis acceptance failed.")

    elapsed = time.monotonic() - started
    status = {
        "experiment": "E16",
        "stage": "S16.7",
        "status": "generated_not_yet_compiled",
        "run_id": run_id,
        "source_s16_5_run": str(s16_5),
        "source_s16_6_run": str(s16_6),
        "generated_latex_files": len(generated_files),
        "copied_figure_files": len(copied),
        "acceptance_passed": int(checks["passed"].sum()),
        "acceptance_total": len(checks),
        "elapsed_seconds": elapsed,
        "completed_at": datetime.now(timezone).isoformat(),
    }
    (run_dir / "run_status.json").write_text(json.dumps(status, indent=2), encoding="utf-8")
    (empirical / "runs/latest_e16_s16_7_run.txt").write_text(str(run_dir) + "\n", encoding="utf-8")
    return run_dir


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description="Generate traceable S16.7 manuscript artifacts")
    parser.add_argument("--project", required=True)
    return parser


def main() -> None:
    print(run(build_parser().parse_args()))


if __name__ == "__main__":
    main()
